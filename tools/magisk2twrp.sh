#!/usr/bin/env bash
#
# magisk2twrp.sh - turn a Magisk module zip into a hybrid TWRP-flashable zip.
#
# The generated zip:
#   * still installs as a regular Magisk module (module.prop + #MAGISK
#     marker, same trick data/patch.zip uses), and
#   * when flashed in TWRP, extracts the module's partition trees
#     (system/ system_ext/ product/ vendor/ odm/) into the real partitions
#     and writes root-level nvram.img / nvdata.img to their partitions.
#
# Dynamic ("super") partition layouts are handled at flash time by the
# generated recovery installer: it probes /dev/block/mapper/<part> first
# (where TWRP maps logical partitions and symlinks them), then the
# bootdevice / by-name paths, and fails with clear instructions when a
# partition cannot be opened read-write (RO2RW case).
#
# Optional: an executable-free hook named twrp-extra.sh in the module zip
# is run from the recovery installer after the extraction (e.g. chcon).
#
# Requires: bash, zip, unzip (Linux/macOS host; CI uses ubuntu).
#
# Usage:
#   tools/magisk2twrp.sh <module.zip> [output.zip]
#
set -euo pipefail

say() { printf '>> %s\n' "$*"; }
die() { printf 'ERROR: %s\n' "$*" >&2; exit 1; }

MOD="${1:-}"
[ -n "$MOD" ] || die "usage: $(basename "$0") <module.zip> [output.zip]"
[ -f "$MOD" ] || die "no such file: $MOD"
command -v zip >/dev/null 2>&1 || die "'zip' is required"
command -v unzip >/dev/null 2>&1 || die "'unzip' is required"

# --- read the module manifest -------------------------------------------
MODPROP="$(unzip -p "$MOD" module.prop 2>/dev/null || true)"
[ -n "$MODPROP" ] || die "'$MOD' does not contain module.prop - not a Magisk module zip"

prop() { printf '%s\n' "$MODPROP" | sed -n "s/^$1[[:space:]]*=[[:space:]]*//p" | head -n1; }
ID="$(prop id)"
NAME="$(prop name)"
VERSION="$(prop version)"
[ -n "$ID" ] || die "module.prop has no 'id'"
case "$ID" in
  *[!A-Za-z0-9._-]*|'') die "module id '$ID' contains unsupported characters" ;;
esac
[ -n "$NAME" ] || NAME="$ID"
# these end up inside generated shell code; keep them boring
SAFE_NAME="$(printf '%s' "$NAME" | tr -cd 'A-Za-z0-9 ._+,()/#@:;&-')"
SAFE_VERSION="$(printf '%s' "$VERSION" | tr -cd 'A-Za-z0-9 ._+,-')"
[ -n "$SAFE_NAME" ] || SAFE_NAME="$ID"

OUT="${2:-out/${ID}-twrp.zip}"
OUTDIR="$(dirname "$OUT")"
mkdir -p "$OUTDIR"
OUT_ABS="$(cd "$OUTDIR" && pwd)/$(basename "$OUT")"
MOD_ABS="$(cd "$(dirname "$MOD")" && pwd)/$(basename "$MOD")"
[ "$OUT_ABS" != "$MOD_ABS" ] || die "output must not overwrite the input zip"

# --- scan the module -----------------------------------------------------
# NOTE: count-based matching on purpose; `grep -q` closes the pipe early and
# the resulting SIGPIPE can trip `set -o pipefail` nondeterministically.
ENTRIES="$(unzip -Z1 "$MOD")"
count_entries() { printf '%s\n' "$ENTRIES" | grep -c "$1" || true; }
PARTS=""
for p in system system_ext product vendor odm; do
  if [ "$(count_entries "^$p/")" -gt 0 ]; then PARTS="$PARTS $p"; fi
done
PARTS="${PARTS# }"
IMAGES=""
for i in nvram nvdata; do
  if [ "$(count_entries "^$i\.img$")" -gt 0 ]; then IMAGES="$IMAGES $i"; fi
done
IMAGES="${IMAGES# }"
EXTRA=0
if [ "$(count_entries '^twrp-extra.sh$')" -gt 0 ]; then EXTRA=1; fi

[ -n "$PARTS$IMAGES" ] || die "'$MOD' has nothing to convert (no partition dirs, no nvram.img/nvdata.img)"

# --- stage the payload ---------------------------------------------------
WORK="$(mktemp -d "${TMPDIR:-/tmp}/magisk2twrp.XXXXXX")"
trap 'rm -rf "$WORK"' EXIT
BUILD="$WORK/build"
mkdir -p "$BUILD"
# umask 0: keep the modes stored in the zip while staging on the host
( umask 0; unzip -o -q "$MOD" -d "$BUILD" )
rm -rf "$BUILD/META-INF"

META="$BUILD/META-INF/com/google/android"
mkdir -p "$META"

# --- generated helper: chmod lines for one staged partition tree ---------
# mode_lines <part>  -> lines like: chmod 755 "$T/bin/tool"
mode_lines() {
  local part="$1" m f esc
  ( cd "$BUILD" && find "$part" -type f -printf '%m %P\n' ) | while read -r m f; do
    [ "$m" = "644" ] && continue
    esc="$(printf '%s' "$f" | sed 's/[\\"$`]/\\&/g')"
    printf '  chmod %s "$T/%s"\n' "$m" "$esc"
  done
}

# --- update-binary: hybrid Magisk/recovery shim ---------------------------
cat > "$META/update-binary" <<SHIM
#!/sbin/sh
#
# Hybrid installer for ${SAFE_NAME} (${ID}) - generated by tools/magisk2twrp.sh
#
#   * Magisk app / BOOTMODE  -> installs as a regular Magisk module
#   * recovery (TWRP)        -> runs META-INF/com/google/android/twrp-install.sh
#
umask 022

OUTFD=\$2
ZIPFILE=\$3
ui_print() { echo "\$1"; }

require_new_magisk() {
  ui_print "*******************************"
  ui_print " Please install Magisk v20.4+! "
  ui_print "*******************************"
  exit 1
}

mount /data 2>/dev/null
[ -f /data/adb/magisk/util_functions.sh ] && . /data/adb/magisk/util_functions.sh
[ -n "\$MAGISK_VER_CODE" ] && [ "\$MAGISK_VER_CODE" -lt 20400 ] && require_new_magisk

if [ -z "\$BOOTMODE" ] || ! \$BOOTMODE; then
  if ! set -o | grep -q standalone; then
    installer="META-INF/com/google/android/twrp-install.sh"
    basedir="\$(dirname "\$0")"
    unzip -o -q -d "\$basedir" "\$ZIPFILE" "\$installer" 2>/dev/null \\
      || /sbin/unzip -o -q -d "\$basedir" "\$ZIPFILE" "\$installer"
    [ -f "\$basedir/\$installer" ] || { ui_print "! cannot extract \$installer"; exit 1; }
    /sbin/sh "\$basedir/\$installer" "\$@"
    retval=\$?
    [ "\$retval" != 0 ] && exit "\$retval"
  fi
fi

[ -n "\$MAGISK_VER_CODE" ] && install_module
exit 0
SHIM

# --- twrp-install.sh: recovery-side extraction ----------------------------
cat > "$META/twrp-install.sh" <<INSTALLER
#!/sbin/sh
# =====================================================================
#  TWRP recovery installer generated by tools/magisk2twrp.sh
#
#  Module: ${SAFE_NAME} (${ID}) ${SAFE_VERSION}
#
#  Extracts the module's partition trees into the real partitions and
#  writes root-level nvram/nvdata images (if present). Dynamic ("super")
#  layouts: /dev/block/mapper/<part> is probed first, then the
#  TWRP/bootdevice by-name paths.
# =====================================================================
umask 022

ZIPFILE="\$3"
[ -f "\$ZIPFILE" ] || { echo "! zip not found: \$ZIPFILE"; exit 1; }

say()  { echo "\$1"; }
fail() { echo ""; echo "! \$1"; exit 1; }
warn() { echo "! \$1"; }

UNZIP=""
for c in unzip /sbin/unzip /system/bin/unzip /system/xbin/unzip; do
  if command -v "\$c" >/dev/null 2>&1; then UNZIP="\$c"; break; fi
done
[ -n "\$UNZIP" ] || fail "unzip not found - flash this zip from TWRP"

do_mount()  { mount  "\$@" 2>/dev/null || /sbin/mount  "\$@" 2>/dev/null || /system/bin/mount  "\$@" 2>/dev/null; }
do_umount() { umount "\$@" 2>/dev/null || /sbin/umount "\$@" 2>/dev/null || /system/bin/umount "\$@" 2>/dev/null; }

part_devices() {
  echo "/dev/block/mapper/\$1"
  echo "/dev/block/platform/bootdevice/by-name/\$1"
  echo "/dev/block/platform/mtk-msdc.0/by-name/\$1"
  echo "/dev/block/by-name/\$1"
}

unmount_mp() { do_umount "\$1" 2>/dev/null; return 0; }

# mount_mp <part> <mountpoint>
mount_mp() {
  _part="\$1"; _mp="\$2"
  mkdir -p "\$_mp" 2>/dev/null
  for _dev in \$(part_devices "\$_part"); do
    [ -e "\$_dev" ] || continue
    unmount_mp "\$_mp"
    for _opts in "-t ext4" "-t auto" ""; do
      # shellcheck disable=SC2086
      if do_mount -o rw \$_opts "\$_dev" "\$_mp"; then
        if ( touch "\$_mp/.magisk2twrp.test" 2>/dev/null && rm -f "\$_mp/.magisk2twrp.test" ); then
          say "  mounted \$_part (rw) from \$_dev"
          return 0
        fi
        warn "  \$_part mounted read-only from \$_dev"
        unmount_mp "\$_mp"
      fi
    done
  done
  return 1
}

extract_tree() {
  say "  extracting \$1 -> \$2"
  \$UNZIP -o -q "\$ZIPFILE" "\$1/*" -d "\$2" || fail "extracting \$1 failed (read-only or full filesystem?)"
}

# system needs system-as-root handling: mounted at /system_root the image
# root contains system/..., mounted at /system it contains the system tree.
install_system() {
  if mount_mp system /system_root; then
    if [ -e /system_root/system/build.prop ] || [ -d /system_root/system/framework ]; then
      # shellcheck disable=SC2034  # T is consumed by the generated chmod lines
      T="/system_root/system"
      extract_tree system /system_root
      unmount_mp /system_root
      return 0
    fi
    unmount_mp /system_root
  fi
  mount_mp system /system || fail "cannot mount system read-write (dynamic partition not mapped, or read-only image - see README note about RO2RW)"
  T="/system"
  extract_tree system /
  unmount_mp /system
}

install_tree() {
  mount_mp "\$1" "/\$1" || fail "cannot mount /\$1 read-write (dynamic partition not mapped, or read-only image - see README note about RO2RW)"
  # shellcheck disable=SC2034  # T is consumed by the generated chmod lines
  T="/\$1"
  extract_tree "\$1" /
  unmount_mp "/\$1"
}

flash_image() {
  _part="\$1"; _img="\$2"
  unmount_mp "/\$_part"
  if grep -qs " /\$_part " /proc/mounts; then
    fail "/\$_part is still mounted - unmount it in TWRP (Mount menu) and flash again"
  fi
  for _dev in \$(part_devices "\$_part"); do
    [ -e "\$_dev" ] || continue
    say "  flashing \$_img -> \$_dev"
    if \$UNZIP -p "\$ZIPFILE" "\$_img" > "\$_dev"; then
      sync
      return 0
    fi
    warn "  write to \$_dev failed"
  done
  return 1
}
INSTALLER

# --- generated run section ------------------------------------------------
{
  printf '\nsay "Installing %s"\nsay "=============================================="\n\n' "$SAFE_NAME"

  for i in $IMAGES; do
    printf 'flash_image %s %s.img || fail "failed to write %s.img"\n' "$i" "$i" "$i"
  done
  [ -n "$IMAGES" ] && printf '\n'

  for p in $PARTS; do
    if [ "$p" = "system" ]; then
      printf 'install_system\n'
    else
      printf 'install_tree %s\n' "$p"
    fi
    mode_lines "$p"
    printf '\n'
  done

  if [ "$EXTRA" = "1" ]; then
    cat <<'EXTRA'

# optional module hook (twrp-extra.sh in the module zip)
mkdir -p /tmp/magisk2twrp-extra
if $UNZIP -o -q "$ZIPFILE" twrp-extra.sh -d /tmp/magisk2twrp-extra >/dev/null 2>&1; then
  say "  running twrp-extra.sh"
  if ! ZIPFILE="$ZIPFILE" /sbin/sh /tmp/magisk2twrp-extra/twrp-extra.sh; then
    warn "twrp-extra.sh failed (continuing)"
  fi
fi
EXTRA
  fi

  printf '\nsync\nsay "Done - reboot to finish installing %s"\nexit 0\n' "$SAFE_NAME"
} >> "$META/twrp-install.sh"

# --- updater-script: only carries the #MAGISK marker ----------------------
cat > "$META/updater-script" <<MAGISK
#MAGISK
# Hybrid Magisk module / TWRP flashable zip for ${SAFE_NAME} (${ID}).
# The real installers are META-INF/com/google/android/update-binary (hybrid
# shim) and META-INF/com/google/android/twrp-install.sh (recovery). This
# file only carries the #MAGISK marker expected by module-aware installers.
ui_print("Installing ${SAFE_NAME}");
MAGISK

chmod 755 "$META/update-binary" "$META/twrp-install.sh"

# --- build the output zip -------------------------------------------------
( cd "$BUILD" && zip -r -X -q "$OUT_ABS" . )

say "$OUT_ABS"
say "  module:     $NAME ($ID) $VERSION"
[ -n "$PARTS" ]  && say "  partitions: $PARTS"
[ -n "$IMAGES" ] && say "  images:     $IMAGES"
[ "$EXTRA" = "1" ] && say "  hook:       twrp-extra.sh"
say "flash it in TWRP; it still installs from the Magisk app as well"
unzip -l "$OUT_ABS" | tail -1
